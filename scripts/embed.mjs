// Writes src/generated.ts: the engine and the 16 levels as base64, because the host's sandbox
// blocks every network request (connect-src 'none'), so nothing may be fetched at runtime.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const wasm = readFileSync("target/wasm32-unknown-unknown/release/jiro_wasm.wasm");
const names = readdirSync("levels").filter((name) => name.endsWith(".bin")).sort();
const levels = names.map((name) => [name.replace(/^\d+-|\.bin$/g, ""), readFileSync(`levels/${name}`).toString("base64")]);
const out = `// Generated by scripts/embed.mjs; do not edit.
export const ENGINE_BASE64 = "${wasm.toString("base64")}";
export const LEVELS_BASE64: [string, string][] = ${JSON.stringify(levels)};
`;
writeFileSync("src/generated.ts", out);
console.log(`embedded engine ${wasm.length} bytes, ${levels.length} levels`);
